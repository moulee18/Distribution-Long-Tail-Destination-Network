import time
from datetime import datetime, timezone, timedelta
from typing import Any, Dict, List, Optional
from sqlalchemy.ext.asyncio import AsyncSession
from sqlalchemy import select

from backend.app.models.entities import (
    Destination,
    Connection,
    CertificationRun,
    CertificationEvidence,
    Alert,
)
from backend.app.schemas.connector_contract import (
    RenditionData,
    DestinationData,
    ConnectionData,
)
from backend.app.connectors.registry import registry
from backend.app.core.errors import IncuBrixException, ErrorCode
from backend.app.core.logging import logger
from backend.app.core.config import settings

class CertificationHarness:
    @staticmethod
    async def certify_destination(
        destination_id: str,
        target_level: str,
        db: AsyncSession,
    ) -> CertificationRun:
        start_time = time.time()
        dest_stmt = select(Destination).where(Destination.id == destination_id)
        dest_res = await db.execute(dest_stmt)
        dest = dest_res.scalar_one_or_none()
        if not dest:
            raise IncuBrixException(ErrorCode.RESOURCE_NOT_FOUND, f"Destination {destination_id} not found", 404)

        conn_stmt = select(Connection).where(Connection.destination_id == dest.id)
        conn_res = await db.execute(conn_stmt)
        connection = conn_res.scalar_one_or_none()
        if not connection:
            connection = Connection(
                destination_id=dest.id,
                connector_key=dest.connector_key,
                settings={"base_url": dest.url, "simulation": True},
            )
            db.add(connection)
            await db.flush()

        # Create certification run
        run = CertificationRun(
            destination_id=dest.id,
            connector_key=dest.connector_key,
            status="running",
            tested_level=target_level,
            resulting_level="L0",
            cleanup_status="pending",
        )
        db.add(run)
        await db.flush()

        connector = registry.get_connector(dest.connector_key)
        dest_dto = DestinationData(
            name=dest.name,
            url=dest.url,
            platform_key=dest.platform_key,
            surface=dest.surface,
            category=dest.category,
            audience_tags=dest.audience_tags or [],
            language=dest.language or "en",
            geo=dest.geo or "GLOBAL",
            est_audience=dest.est_audience or 0,
            rules_url=dest.rules_url,
            frequency_cap=dest.frequency_cap,
            self_promo_allowed=dest.self_promo_allowed,
            link_policy=dest.link_policy,
            disclosure_required=dest.disclosure_required,
            automation_allowed=dest.automation_allowed,
            connector_key=dest.connector_key,
            relevance_score=dest.relevance_score,
            level=dest.level,
        )
        conn_dto = ConnectionData(
            credentials=connection.encrypted_credentials or {},
            settings=connection.settings or {},
        )

        test_rendition = RenditionData(
            title=f"[CERTIFICATION TEST] Sandbox Verification - {int(time.time())}",
            body="This is an automated test post generated by the IncuBrix Certification Harness to verify endpoint stability and cleanup compliance. Will be deleted immediately.",
            tags=["test", "incubrix"],
            is_promotional=False,
            contains_ai_content=False,
        )

        try:
            # Step 1: Validate
            val_res = await connector.validate(test_rendition, dest_dto, conn_dto)
            ev1 = CertificationEvidence(
                run_id=run.id,
                step="validate",
                request_data=test_rendition.model_dump(),
                response_data=val_res.model_dump(),
                status_code=200 if val_res.ok else 400,
            )
            db.add(ev1)
            if not val_res.ok:
                raise IncuBrixException(ErrorCode.DEST_SPEC_VIOLATION, f"Validation step failed: {val_res.violations}")

            # For Assisted connector:
            if dest.connector_key == "assisted" or target_level == "L1":
                assist_res = await connector.build_assist_pack(test_rendition, dest_dto)
                ev_assist = CertificationEvidence(
                    run_id=run.id,
                    step="build_assist_pack",
                    request_data={"destination": dest.name},
                    response_data=assist_res.model_dump(),
                    status_code=200,
                )
                db.add(ev_assist)
                run.status = "success"
                run.resulting_level = "L1"
                run.cleanup_status = "not_applicable"
                dest.level = "L1"
                dest.last_certified_at = datetime.now(timezone.utc)
                run.duration_ms = int((time.time() - start_time) * 1000)
                await db.commit()
                return run

            # Step 2: Publish Test Post
            idempotency_key = f"cert_{run.id[:8]}_{int(time.time())}"
            pub_res = await connector.publish(test_rendition, dest_dto, conn_dto, idempotency_key)
            ev2 = CertificationEvidence(
                run_id=run.id,
                step="publish",
                request_data={"idempotency_key": idempotency_key},
                response_data=pub_res.model_dump(),
                status_code=200,
            )
            db.add(ev2)
            run.platform_post_id = pub_res.platform_post_id
            run.live_url = pub_res.live_url

            # Step 3: Verify Status
            status_res = await connector.get_status(pub_res.platform_post_id, conn_dto)
            ev3 = CertificationEvidence(
                run_id=run.id,
                step="get_status",
                request_data={"platform_post_id": pub_res.platform_post_id},
                response_data=status_res.model_dump(),
                status_code=200,
            )
            db.add(ev3)
            if status_res.status not in ("live", "published", "manual_action_required"):
                raise IncuBrixException(ErrorCode.PLATFORM_UNAVAILABLE, f"Status check failed: got {status_res.status}")

            # Step 4: Optional Metrics (for L4)
            achieved_level = "L3"
            if target_level == "L4" and "metrics" in connector.manifest.capabilities:
                try:
                    metrics_res = await connector.fetch_metrics(pub_res.platform_post_id, conn_dto)
                    ev_m = CertificationEvidence(
                        run_id=run.id,
                        step="fetch_metrics",
                        request_data={"platform_post_id": pub_res.platform_post_id},
                        response_data=metrics_res.model_dump(),
                        status_code=200,
                    )
                    db.add(ev_m)
                    achieved_level = "L4"
                except Exception as me:
                    logger.warning(f"Metrics verification failed during L4 test: {str(me)}")

            # Step 5: Cleanup / Delete test post within 10 minutes
            del_res = await connector.delete(pub_res.platform_post_id, conn_dto)
            ev4 = CertificationEvidence(
                run_id=run.id,
                step="delete",
                request_data={"platform_post_id": pub_res.platform_post_id},
                response_data=del_res.model_dump(),
                status_code=200,
            )
            db.add(ev4)

            if not del_res.deleted:
                run.cleanup_status = "failed"
                raise IncuBrixException(ErrorCode.INTERNAL_ERROR, "Post deletion failed during certification cleanup")
            run.cleanup_status = "deleted"

            # Step 6: Verify Deletion
            post_del_status = await connector.get_status(pub_res.platform_post_id, conn_dto)
            ev5 = CertificationEvidence(
                run_id=run.id,
                step="verify_deleted",
                request_data={"platform_post_id": pub_res.platform_post_id},
                response_data=post_del_status.model_dump(),
                status_code=200,
            )
            db.add(ev5)

            # Success
            run.status = "success"
            run.resulting_level = achieved_level
            dest.level = achieved_level
            dest.last_certified_at = datetime.now(timezone.utc)
            dest.enabled = True

        except Exception as e:
            run.status = "failed"
            run.failure_reason = str(e)
            dest.level = "L0"  # Demote to L0 on failure!
            dest.enabled = False
            # Raise alert for destination failure
            alert = Alert(
                severity="warning",
                source="CertificationHarness",
                title=f"Certification Failed for {dest.name}",
                message=f"Destination {dest.name} ({dest.id}) failed certification at level {target_level}: {str(e)}. Demoted to L0.",
            )
            db.add(alert)

        run.duration_ms = int((time.time() - start_time) * 1000)
        await db.commit()
        return run

    @staticmethod
    async def run_scheduled_recertification(db: AsyncSession) -> List[CertificationRun]:
        """
        Recertifies destinations where last_certified_at is older than 30 days
        or never certified. Demotes any failing destination.
        """
        cutoff = datetime.now(timezone.utc) - timedelta(days=settings.RECERTIFICATION_INTERVAL_DAYS)
        stmt = select(Destination).where(
            (Destination.last_certified_at == None) | (Destination.last_certified_at < cutoff)
        )
        res = await db.execute(stmt)
        destinations = list(res.scalars().all())
        runs = []
        for d in destinations:
            target = "L1" if d.connector_key == "assisted" else ("L4" if d.level == "L4" else "L3")
            run = await CertificationHarness.certify_destination(d.id, target, db)
            runs.append(run)
        return runs

certification_harness = CertificationHarness()
